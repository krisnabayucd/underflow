import assert from 'node:assert/strict';
import {trend,decorate,retain,changeSince} from '../lib/signals.ts';
import {encode,decode} from '../lib/storage.ts';
const now=Date.UTC(2026,9,12),day=86400;
const points=Array.from({length:10},(_,i)=>[now/1000-(10-i)*day,i<7?100:200]);
assert.equal(trend(points,now).sustained,true);
assert.equal(trend([...points.slice(0,9),[points[9][0],10000]],now).sustained,true);
assert.equal(trend(points.map((p,i)=>[p[0],i===8?100:p[1]]),now).sustained,false);
assert.equal(trend(points.slice(1),now).sustained,false);
assert.equal(trend(points.map(([t,v])=>[t,v/100]),now).sustained,false);
const tiny={fees:50,fees7d:70,feeChange:1000};
assert.equal(decorate(tiny).score,25);
assert.equal(decorate({...tiny,fees7d:7000,feeChange:100}).score,60);
const sourceNames=['DefiLlama protocols','DefiLlama fees','DefiLlama revenue'];
const old={at:10,projects:[{id:'x',fees:100,revenue:20}],sources:sourceNames.map(name=>({name,status:'ok',at:10})),watch:[{address:'a',status:'ok',price:1}],network:[]};
const fresh=()=>({at:20,projects:[{id:'x',fees:null,revenue:30}],sources:sourceNames.map(name=>({name,status:name.endsWith('fees')?'unavailable':'ok',at:20})),watch:[{address:'a',status:'unavailable'}],network:[]});
const retained=retain(fresh(),old);
assert.equal(retained.projects[0].fees,100);
assert.equal(retained.projects[0].revenue,30);
assert.equal(retained.projects[0].metricAt.fees,10);
assert.equal(retained.watch[0].price,1);
assert.equal(retained.watch[0].at,10);
assert.equal(changeSince({id:'x',score:60,stale:true},{x:{score:25}}),'');
assert.equal(changeSince({id:'x',score:60,metricAt:{fees:20}},{x:{score:25,at:10}}),'Strengthening');
assert.deepEqual(await decode(await encode(retained)),JSON.parse(JSON.stringify(retained)));
assert.deepEqual(await decode(JSON.stringify(old)),old);
console.log('Signal thresholds, daily continuity, source fallback, visit comparison and storage checks passed');
